#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
GEN="$SCRIPT_DIR/generate.sh"

bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/h264_420_8bit_256x128.nv12.raw"
bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/h264_profile0_256x128.nv12.raw"
bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/h264_profile1_256x128.nv12.raw"
bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/h264_profile2_256x128.nv12.raw"
bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/h264_profile3_256x128.nv12.raw"
bash "$GEN" raw nv12 256 128 "$SCRIPT_DIR/hevc_420_8bit_256x128.nv12.raw"
bash "$GEN" raw p010le 256 128 "$SCRIPT_DIR/hevc_420_p10_main10_256x128.p010le.raw"
bash "$GEN" raw nv16 256 128 "$SCRIPT_DIR/hevc_nv16_422_input_256x128.nv16.raw"
bash "$GEN" raw p210le 256 128 "$SCRIPT_DIR/hevc_p210_422_input_main10_256x128.p210le.raw"
bash "$GEN" raw nv12 264 128 "$SCRIPT_DIR/h264_420_8bit_264x128.nv12.raw"
bash "$GEN" raw nv12 256 136 "$SCRIPT_DIR/h264_420_8bit_256x136.nv12.raw"
bash "$GEN" raw nv12 264 128 "$SCRIPT_DIR/hevc_420_8bit_264x128.nv12.raw"
bash "$GEN" raw nv12 256 136 "$SCRIPT_DIR/hevc_420_8bit_256x136.nv12.raw"
bash "$GEN" raw nv12 8192 8192 "$SCRIPT_DIR/h264_420_8bit_8192x8192.nv12.raw"
bash "$GEN" raw nv12 8192 8192 "$SCRIPT_DIR/hevc_420_8bit_8192x8192.nv12.raw"

bash "$GEN" h264 256 128 "$SCRIPT_DIR/h264_420_256x128.264"
bash "$GEN" h264profile baseline 5.2 4096 2304 "$SCRIPT_DIR/h264_baseline_l52_4096x2304.264"
bash "$GEN" h264profile main 5.2 4096 2304 "$SCRIPT_DIR/h264_main_l52_4096x2304.264"
bash "$GEN" h264profile high 5.2 4096 2304 "$SCRIPT_DIR/h264_high_l52_4096x2304.264"
bash "$GEN" h264fmt 256 128 yuv422p "$SCRIPT_DIR/h264_422_256x128.264"
bash "$GEN" h264fmt 256 128 yuv444p "$SCRIPT_DIR/h264_444_256x128.264"
bash "$GEN" hevc 256 128 yuv420p "$SCRIPT_DIR/hevc_420_256x128.265"
bash "$GEN" hevc 256 128 yuv420p10le "$SCRIPT_DIR/hevc_420p10_256x128.265"
bash "$GEN" hevcprofile main 5.1 high 4096 2160 yuv420p "$SCRIPT_DIR/hevc_main_l51_high_4096x2160.265"
bash "$GEN" hevcprofile main10 5.1 high 4096 2160 yuv420p10le "$SCRIPT_DIR/hevc_main10_l51_high_4096x2160.265"
bash "$GEN" hevc 256 128 yuv422p "$SCRIPT_DIR/hevc_422_256x128.265"
bash "$GEN" hevc 256 128 yuv444p "$SCRIPT_DIR/hevc_444_256x128.265"
bash "$GEN" h264 1920 1080 "$SCRIPT_DIR/h264_420_1920x1080.264"
bash "$GEN" h264 8192 8192 "$SCRIPT_DIR/h264_420_8192x8192.264"
bash "$GEN" hevc 8192 8192 yuv420p "$SCRIPT_DIR/hevc_420_8192x8192.265"
bash "$GEN" vp9 256 128 "$SCRIPT_DIR/vp9_420_256x128.vp9"

echo "PASS: generated all codec capability assets in $SCRIPT_DIR"
